def opener(lang, first):
    """Keep the requested opener unless it is already used 10 times; then pick the least-used fitting one."""
    pool = [12] if lang == "hi" else [4, 10] + [i for i in range(15) if i not in (4, 10, 12)] if lang == "hinglish"         else [i for i in range(15) if i not in (4, 10, 12)]
    idx = O.index(first)
    if USE.get(idx, 0) >= 10 or idx not in pool:
        idx = min(pool, key=lambda i: USE.get(i, 0))
    USE[idx] = USE.get(idx, 0) + 1
    return O[idx]


